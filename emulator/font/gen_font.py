#!/usr/bin/env python3
"""Generate src/font.zig, the font of the window, from spleen-16x32.bdf.

The font has the glyphs of Spleen for the codes 0x20 to 0xFF, ISO 8859-1.
The codes below 0x20, and those that Spleen has no glyph for (0x80 to
0x9F), are blank, as on NiceMonMEGA65. Spleen is licensed under the BSD
2-Clause license, see LICENSE.spleen.

The font file is not in this repository. src/font.zig is from version
2.2.0, the tag 2.2.0 of the Spleen repository. Usage, from emulator/:

    git clone --branch 2.2.0 https://github.com/fcambus/spleen
    python3 font/gen_font.py spleen/spleen-16x32.bdf > src/font.zig
"""

import sys

WIDTH = 16
HEIGHT = 32


def fail(msg: str) -> None:
    sys.exit(f"gen_font.py: {msg}")


def load_bdf(path: str) -> tuple[str, dict[int, list[int]]]:
    """Return the version and the rows of each glyph below 256."""
    version = ""
    glyphs: dict[int, list[int]] = {}
    code = -1
    rows: list[int] | None = None
    with open(path, encoding="ascii") as f:
        for n, line in enumerate(f, 1):
            words = line.split()
            if not words:
                continue
            if words[0] == "FONT_VERSION":
                version = words[1].strip('"')
            elif words[0] == "ENCODING":
                code = int(words[1])
            elif words[0] == "BBX" and words[1:3] != [str(WIDTH), str(HEIGHT)]:
                fail(f"line {n}: glyph {code} is not {WIDTH}x{HEIGHT}")
            elif words[0] == "BITMAP":
                rows = []
            elif words[0] == "ENDCHAR":
                if rows is None or len(rows) != HEIGHT:
                    fail(f"line {n}: glyph {code} has no {HEIGHT} rows")
                elif 0 <= code < 256:
                    glyphs[code] = rows
                rows = None
            elif rows is not None:
                rows.append(int(words[0], 16))
    if not version:
        fail("no FONT_VERSION")
    return version, glyphs


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: gen_font.py spleen-16x32.bdf > src/font.zig")
    version, glyphs = load_bdf(sys.argv[1])
    blank = [0] * HEIGHT
    print(f"//! The font of the window: Spleen {WIDTH}x{HEIGHT} {version}, BSD 2-Clause")
    print("//! license (font/LICENSE.spleen). Generated by font/gen_font.py; do not")
    print("//! edit. Each glyph is 32 rows from the top, and bit 15 of a row is its")
    print("//! leftmost pixel. Codes without a glyph are blank.")
    print()
    print(f"pub const width = {WIDTH};")
    print(f"pub const height = {HEIGHT};")
    print()
    print(f"pub const glyphs = [256][{HEIGHT}]u16{{")
    for code in range(256):
        rows = glyphs.get(code, blank) if code >= 0x20 else blank
        print("    .{ " + ", ".join(f"0x{r:04X}" for r in rows) + f" }}, // 0x{code:02X}")
    print("};")


if __name__ == "__main__":
    main()
