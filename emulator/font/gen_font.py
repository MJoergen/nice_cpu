#!/usr/bin/env python3
"""Generate src/font.zig, the font of the window, from spleen-16x32.bdf.

The font has the glyphs of Spleen for the codes 0x20 to 0xFF, ISO 8859-1.
The codes 0x80 to 0x99, which ISO 8859-1 has no glyph for, hold blocks
and arrows (DEVICES.md 1.8): the code of each is the low byte of its
Unicode code point, U+2580 to U+258F at 0x80 to 0x8F, and U+2190 to
U+2199 at 0x90 to 0x99. Spleen has all of them but the four diagonal
arrows, U+2196 to U+2199, whose rows are below: ARROW_NE, mirrored for
the other three. The codes below 0x20, 0x7F, and 0x9A to 0x9F are blank.
Spleen is licensed under the BSD 2-Clause license, see LICENSE.spleen.

The font file is not in this repository. src/font.zig is from version
2.2.0, the tag 2.2.0 of the Spleen repository. Usage, from emulator/:

    git clone --branch 2.2.0 https://github.com/fcambus/spleen
    python3 font/gen_font.py spleen/spleen-16x32.bdf > src/font.zig
"""

import sys

WIDTH = 16
HEIGHT = 32

# The code points of the codes 0x80 to 0x99.
EXTRA = {0x80 + i: 0x2580 + i for i in range(16)} | {0x90 + i: 0x2190 + i for i in range(10)}

# U+2197, the north-east arrow, which Spleen lacks: a stroke of 2 pixels
# in the box of columns 1 to 14 and rows 9 to 22, centered in the cell.
ARROW_NE = [0] * 9 + [
    0x01FE, 0x01FE, 0x000E, 0x001E, 0x0036, 0x0066, 0x00C6, 0x0186,
    0x0300, 0x0600, 0x0C00, 0x1800, 0x3000, 0x6000,
] + [0] * 9


def mirror(rows: list[int]) -> list[int]:
    """Return the glyph mirrored left to right."""
    return [int(f"{r:016b}"[::-1], 2) for r in rows]


DRAWN = {
    0x2196: mirror(ARROW_NE),
    0x2197: ARROW_NE,
    0x2198: ARROW_NE[::-1],
    0x2199: mirror(ARROW_NE)[::-1],
}


def fail(msg: str) -> None:
    sys.exit(f"gen_font.py: {msg}")


def load_bdf(path: str) -> tuple[str, dict[int, list[int]]]:
    """Return the version and the rows of each glyph."""
    version = ""
    glyphs: dict[int, list[int]] = {}
    code = -1
    rows: list[int] | None = None
    with open(path, encoding="ascii") as f:
        for n, line in enumerate(f, 1):
            words = line.split()
            if not words:
                continue
            if words[0] == "FONT_VERSION":
                version = words[1].strip('"')
            elif words[0] == "ENCODING":
                code = int(words[1])
            elif words[0] == "BBX" and words[1:3] != [str(WIDTH), str(HEIGHT)]:
                fail(f"line {n}: glyph {code} is not {WIDTH}x{HEIGHT}")
            elif words[0] == "BITMAP":
                rows = []
            elif words[0] == "ENDCHAR":
                if rows is None or len(rows) != HEIGHT:
                    fail(f"line {n}: glyph {code} has no {HEIGHT} rows")
                elif code >= 0:
                    glyphs[code] = rows
                rows = None
            elif rows is not None:
                rows.append(int(words[0], 16))
    if not version:
        fail("no FONT_VERSION")
    return version, glyphs


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: gen_font.py spleen-16x32.bdf > src/font.zig")
    version, glyphs = load_bdf(sys.argv[1])
    for point, rows in DRAWN.items():
        if point in glyphs:
            fail(f"Spleen has U+{point:04X}, which gen_font.py draws")
        glyphs[point] = rows
    for code, point in EXTRA.items():
        if point not in glyphs:
            fail(f"no glyph for U+{point:04X}")
        glyphs[code] = glyphs[point]
    blank = [0] * HEIGHT
    print(f"//! The font of the window: Spleen {WIDTH}x{HEIGHT} {version}, BSD 2-Clause")
    print("//! license (font/LICENSE.spleen). Generated by font/gen_font.py; do not")
    print("//! edit. Each glyph is 32 rows from the top, and bit 15 of a row is its")
    print("//! leftmost pixel. Codes without a glyph are blank. The codes 0x80 to")
    print("//! 0x99 are U+2580 to U+258F and U+2190 to U+2199; U+2196 to U+2199 are")
    print("//! drawn by gen_font.py, not Spleen's.")
    print()
    print(f"pub const width = {WIDTH};")
    print(f"pub const height = {HEIGHT};")
    print()
    print(f"pub const glyphs = [256][{HEIGHT}]u16{{")
    for code in range(256):
        rows = blank if code < 0x20 or 0x9A <= code < 0xA0 else glyphs.get(code, blank)
        print("    .{ " + ", ".join(f"0x{r:04X}" for r in rows) + f" }}, // 0x{code:02X}")
    print("};")


if __name__ == "__main__":
    main()
